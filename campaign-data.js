          successTarget = choice.branchValue==='careful' ? careful.id : choice.branchValue==='bold' ? bold.id : empathic.id;
          failureTarget = choice.branchValue==='careful' ? bold.id : choice.branchValue==='bold' ? empathic.id : careful.id;
