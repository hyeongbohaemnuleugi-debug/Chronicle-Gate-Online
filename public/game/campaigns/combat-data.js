/**
 * Chronicle Gate v15 — original campaign professions and contextual encounters.
 * Story modules remain the source of branching fiction. Each encounter interrupts
 * one mandatory investigation hub and releases that same scene after victory.
 * The four profession slots retain might / agility / wit / heart primary bonuses
 * so legacy saves and campaign switching can migrate by slot without random stats.
 */
const STAT_NAMES = { might: '힘', agility: '민첩', wit: '통찰', heart: '교섭' };
const PRESETS = {
  might: { might: 3, agility: 1, wit: 0, heart: 1 },
  agility: { might: 1, agility: 3, wit: 1, heart: 0 },
  wit: { might: 0, agility: 1, wit: 3, heart: 1 },
  heart: { might: 1, agility: 0, wit: 1, heart: 3 },
};
const RULES = {
  strike: '공격 판정. 성공 3 · 부분 성공 1 · 대성공 4 피해. 전투당 1회.',
  drain: '공격 판정. 성공 2 · 부분 성공 1 · 대성공 3 피해. 적중하면 자신의 생명 1 회복. 전투당 1회.',
  expose: '판정 없이 피해 1. 이후 일행이 적중시키는 공격 2회에 피해 +1. 전투당 1회.',
  stun: '판정 없이 피해 1. 다음 적 행동 1회를 막음. 전투당 1회, 행동 방해는 중첩되지 않음.',
  guard: '판정 없이 피해 1. 선택한 생존 동료에게 보호막 2(최대 3). 자신도 선택 가능. 전투당 1회.',
  heal: '판정 없이 피해 1. 선택한 생존 동료의 생명 1 회복, 보호막 1(최대 3). 자신도 선택 가능. 전투당 1회.',
  rally: '판정 없이 피해 1. 살아 있는 일행 모두 다음 공격 판정 +2(중첩 불가). 지원 기술에는 소모되지 않음. 전투당 1회.',
};
function profession(id, name, description, main, basicName, basicText, abilityName, type, abilityText) {
  const target = ['guard', 'heal'].includes(type) ? 'ally' : type === 'rally' ? 'all' : 'enemy';
  return {
    id, name, description,
    stats: { ...PRESETS[main] },
    basic: { name: basicName, stat: main, text: basicText },
    ability: {
      name: abilityName, type,
      ...(['strike', 'drain'].includes(type) ? { stat: main } : {}),
      text: abilityText,
      description: `${['strike', 'drain'].includes(type) ? `D20 + ${STAT_NAMES[main]}. ` : ''}${RULES[type]}`,
      target,
    },
  };
}
