/** v24 authored optional encounters. All dialogue is local, finite, and replayable.
 * A failed negotiation can cost time; only the displayed fumble starts combat.
 * Avoiding an encounter never grants its combat-victory flag or damages a player.
 */
const attack = (name,text,target='actor',dc=12) => ({name,text,target,damage:1,dc});
const negotiate = (label,stat,dc,texts,callback) => ({
  label,stat,dc,callback,
  outcomes:{
    critical:{text:texts[0],method:'negotiated',pressure:-1},
    success:{text:texts[1],method:'negotiated'},
    failure:{text:texts[2],method:'bypassed',pressure:1},
    fumble:{text:texts[3],method:'fight'},
  },
});
const bypass = (label,text,callback,pressure=1) => ({label,text,callback,pressure});
const item = (id,label,text,callback,consume=false) => ({
  label,text,callback,requires:{item:id},[consume?'consumeItems':'useItems']:[id],
});
const moves = (basic,ability) => {
  if(basic.length!==4||ability.length!==4)throw Error('직업별 공격 문장이 네 개씩 필요합니다.');
  return {basic,ability};
};

